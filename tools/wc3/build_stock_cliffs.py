#!/usr/bin/env python3
"""build_stock_cliffs: derive the stock cliff types of every WC3 tileset from Blizzard / reference maps.
Reads the war3map.w3e header (tileset letter + cliff list) of every .w3m/.w3x (and the maps inside every .w3n) under the
given folders and writes data/wc3/terrain/stock_cliffs.json:
  stock[ts]  = cliff ids listed by at least half of that tileset's maps (the tileset's own pair, e.g. W -> CWsn, CWgr)
  seen[ts]   = every cliff id a reference map of that tileset lists (custom tilesets may borrow other tilesets' cliffs)
  maps[ts]   = number of maps per tileset
Background: an earlier build put 'CWdi' (does not exist) into edgegen for Lordaeron Winter; every cliff of "Wings over Alterac"
rendered as black holes. Ids must come from Blizzard data, never from memory.
Never pass folders with our own maps (they would teach the check our own mistakes).
Usage: build_stock_cliffs.py DIR [DIR ...] [--out data/wc3/terrain/stock_cliffs.json]"""
import sys, os, glob, json, struct, collections
H = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(H, '..', 'lib', 'wc3')]
from mpqread import MPQ
def header(w):
    ts = w[8:9].decode('latin1'); n = struct.unpack_from('<i', w, 13)[0]; p = 17 + 4 * n
    nc = struct.unpack_from('<i', w, p)[0]; p += 4
    return ts, [w[p + 4 * k:p + 4 * k + 4].decode('latin1') for k in range(nc)]
def maps_in(path):
    q = MPQ(open(path, 'rb').read())
    if not path.lower().endswith('.w3n'): yield path, q; return
    for n in (q.read('(listfile)') or b'').decode('latin1').replace('\r', '').split('\n'):
        n = n.strip()
        if n.lower().endswith(('.w3x', '.w3m')):
            try: yield path + '::' + n, MPQ(q.read(n))
            except Exception: pass
def build(dirs):
    cnt = collections.defaultdict(collections.Counter); nm = collections.Counter(); src = {}
    files = sorted({f for d in dirs for e in ('w3m', 'w3x', 'w3n') for f in glob.glob(os.path.join(d, '**', '*.' + e), recursive=True)})
    for f in files:
        try:
            for name, q in maps_in(f):
                w = q.read('war3map.w3e')
                if not w or w[:4] != b'W3E!': continue
                ts, cl = header(w); nm[ts] += 1
                for c in set(cl): cnt[ts][c] += 1; src.setdefault(ts + ':' + c, os.path.basename(name))
        except Exception: continue
    return dict(stock={t: sorted(c for c, k in cnt[t].items() if k * 2 >= nm[t]) for t in sorted(cnt)},
                seen={t: sorted(cnt[t]) for t in sorted(cnt)}, maps=dict(sorted(nm.items())), example=src,
                note='generated by tools/wc3/build_stock_cliffs.py from Blizzard and reference maps; tilesets missing here have no reference map yet')
if __name__ == '__main__':
    a = sys.argv[1:]; out = os.path.join(H, '..', '..', 'data', 'wc3', 'terrain', 'stock_cliffs.json')
    if '--out' in a: i = a.index('--out'); out = a[i + 1]; del a[i:i + 2]
    if not a: print(__doc__); sys.exit(2)
    d = build(a); json.dump(d, open(out, 'w'), indent=1, sort_keys=True)
    for t in d['stock']: print(t, d['maps'][t], 'maps  stock', d['stock'][t], ' seen', d['seen'][t])
    print('wrote', out)
